#!/usr/bin/env python3
"""build_aime100_dataset.py — build the `aime_100` confirmation set + its lm-eval task.

WHY (2026-07-25, AN Gemma-4 E2B): `aime_30` is 30 questions, so one question = 0.0333 and
a 1-2 question move is indistinguishable from noise. `aime_100` is the low-variance
confirmation set: n=100 -> 1 question = 0.01. It exists to confirm (or kill) a MOVED
reading on aime_30, not to replace it.

CONSTRUCTION — AIME 2018-2023, problem-level disjoint from BOTH:
  (a) the SFT training pool `aime_hist` (simpo_run/pool_full.jsonl, 182 unique ids drawn
      from gneubig/aime-1983-2024 with year <= 2023) -> excluded by exact id
      `aime-{Year}-{Problem Number}`, the same id scheme simpo_pool.py:158 emits; and
  (b) the `aime_30` anchor, which is Maxwell-Jia/AIME_2024 -> excluded BY YEAR, since this
      set stops at 2023 and never touches 2024.

Measured availability (2026-07-25): clean-after-exclusion per year
  2018:14  2019:14  2020:22  2021:20  2022:18  2023:18  = 106 -> take 100, stratified.
2020-2023 alone gives only 78, which is why the span starts at 2018. Note gneubig's 2024
slice is INCOMPLETE (14 of 30 problems), a second reason not to source 2024 from it.

Era caveat, stated so it is never silently assumed away: 2018-2023 is modern-era AIME
(I+II, 30/yr) so difficulty is broadly comparable to 2024 — but it is NOT the same year as
the anchor. aime_100 absolute scores are therefore comparable ACROSS MODELS on aime_100,
not directly against an aime_30 number.

Outputs, all inside the lm-eval task dir:
  aime_100.jsonl     the 100 problems           COMMITTED (deterministic given --seed)
  build_report.json  exclusion audit            COMMITTED
  utils_chat.py      symlink to the scorer      COMMITTED
  aime100_chat.yaml  the lm-eval task           GENERATED, git-ignored

The yaml is git-ignored because `dataset_kwargs.data_files` must be an ABSOLUTE path
(HF datasets resolves relative paths against CWD, and lm-eval does not chdir to the task
dir), and that path differs per host — committing one guarantees a stale pointer somewhere.
Materialise it on any host, with no HF access and no training pool, via:

    python eval/build_aime100_dataset.py --yaml-only

The scorer is NOT reimplemented: utils_chat.py in the task dir is a symlink to
aime24_chat/utils_chat.py (the extractor validated at 22/30 on 128e NVFP4A16 vs stock 0/30).

Full rebuild (needs HF + the training pool, to re-prove disjointness):
    HF_TOKEN=... python eval/build_aime100_dataset.py \
        --train-pool /srv/ml/an-finetune/simpo_run/pool_full.jsonl
"""
from __future__ import annotations
import argparse
import collections
import hashlib
import json
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
TASK_DIR = os.path.join(HERE, "lm_eval_tasks", "aime100_chat")

YAML_TMPL = """\
# AIME 2018-2023 confirmation set — {n} problems, problem-level disjoint from the
# aime_hist SFT training pool AND from the aime_30 anchor (Maxwell-Jia/AIME_2024).
# GENERATED by eval/build_aime100_dataset.py — do not hand-edit; re-run the builder.
# Built {stamp} · source gneubig/aime-1983-2024 · seed {seed}
# Scorer: utils_chat.process_results (symlink to aime24_chat/utils_chat.py, unmodified).
task: aime100_chat
dataset_path: json
dataset_kwargs:
  data_files:
    train: {data_path}
training_split: train
fewshot_split: train
test_split: train
output_type: generate_until
doc_to_text: "Question: {{{{Problem}}}}\\nAnswer:"
doc_to_target: "{{{{Answer}}}}"
process_results: !function utils_chat.process_results
metric_list:
  - metric: exact_match
    aggregation: mean
    higher_is_better: true
generation_kwargs:
  until:
    - "Question:"
    - "</s>"
    - "<|im_end|>"
    - "<|eot_id|>"
  do_sample: false
  temperature: 0.0
  max_gen_toks: 32768
repeats: 1
num_fewshot: 0
metadata:
  version: 0.0
"""


def _write_yaml(task_dir: str, seed: int) -> str:
    """Materialise aime100_chat.yaml from the committed jsonl. No HF, no training pool.

    Split out so a fresh clone (or a repo that moved) can rebuild just the host-specific
    absolute `data_files` path, which is the only reason the yaml is not committed.
    """
    import datetime
    data_path = os.path.abspath(os.path.join(task_dir, "aime_100.jsonl"))
    if not os.path.exists(data_path):
        raise SystemExit("missing %s — run a full build (needs HF + --train-pool) first"
                         % data_path)
    n = sum(1 for _ in open(data_path))
    out = os.path.join(task_dir, "aime100_chat.yaml")
    with open(out, "w") as fo:
        fo.write(YAML_TMPL.format(n=n, stamp=datetime.datetime.now().strftime("%Y-%m-%d"),
                                  seed=seed, data_path=data_path))
    print(">>> task   -> %s (n=%d, data_files=%s)" % (out, n, data_path))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--train-pool", default="/srv/ml/an-finetune/simpo_run/pool_full.jsonl",
                    help="SFT pool containing source=aime_hist rows; their ids are EXCLUDED")
    ap.add_argument("--year-min", type=int, default=2018)
    ap.add_argument("--year-max", type=int, default=2023)
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--seed", type=int, default=3407)
    ap.add_argument("--task-dir", default=TASK_DIR)
    ap.add_argument("--yaml-only", action="store_true",
                    help="regenerate ONLY aime100_chat.yaml from the committed jsonl — no HF, "
                         "no training pool. Use this after a fresh clone or a repo move.")
    a = ap.parse_args()
    rng = random.Random(a.seed)

    if a.yaml_only:
        _write_yaml(a.task_dir, a.seed)
        return

    train_ids = set()
    if os.path.exists(a.train_pool):
        for ln in open(a.train_pool):
            r = json.loads(ln)
            if r.get("source") == "aime_hist":
                train_ids.add(r["id"])
    else:
        raise SystemExit("train pool not found: %s — refusing to build a set that cannot be "
                         "proven disjoint from training" % a.train_pool)
    print(">>> aime_hist training ids to exclude: %d" % len(train_ids))

    from datasets import load_dataset
    ds = load_dataset("gneubig/aime-1983-2024", split="train",
                      token=os.environ.get("HF_TOKEN"))

    by_year, excluded, malformed = collections.defaultdict(list), 0, 0
    for i, r in enumerate(ds):
        try:
            y = int(r.get("Year"))
        except (TypeError, ValueError):
            continue
        if not (a.year_min <= y <= a.year_max):
            continue
        # `aime-{Year}-{Problem Number}` COLLIDES between AIME I and AIME II of the same
        # year (both have a problem 5). simpo_pool.py:158 emits this same key, which is why
        # the 200-row aime_hist pool holds only 182 unique ids. Consequences, both handled:
        #   - as an EXCLUSION key it is over-broad: matching it drops BOTH the I and II
        #     problem when only one was trained. That is conservative — it can never leak
        #     training data into the eval — so we keep it as the exclusion key.
        #   - as an eval ROW id it is not unique, so we disambiguate with a content hash.
        excl_key = "aime-%s-%s" % (y, r.get("Problem Number", i))
        if excl_key in train_ids:
            excluded += 1
            continue
        q, ans = (r.get("Question") or "").strip(), str(r.get("Answer") or "").strip()
        if not q or not ans:
            malformed += 1
            continue
        h = hashlib.sha1(q.encode("utf-8")).hexdigest()[:6]
        by_year[y].append({"id": "%s-%s" % (excl_key, h), "excl_key": excl_key,
                           "year": y, "Problem": q, "Answer": ans})

    avail = {y: len(v) for y, v in sorted(by_year.items())}
    total = sum(avail.values())
    print(">>> span %d-%d: clean=%d (excluded-as-training=%d, malformed=%d) per-year=%s"
          % (a.year_min, a.year_max, total, excluded, malformed, avail))
    if total < a.n:
        raise SystemExit("only %d clean problems in %d-%d, need %d — widen --year-min "
                         "(and label the era shift)" % (total, a.year_min, a.year_max, a.n))

    for v in by_year.values():
        rng.shuffle(v)
    sel, keys = [], sorted(by_year)
    while len(sel) < a.n:                      # round-robin across years = even coverage
        for y in keys:
            if by_year[y] and len(sel) < a.n:
                sel.append(by_year[y].pop())
    sel.sort(key=lambda r: (r["year"], r["id"]))

    os.makedirs(a.task_dir, exist_ok=True)
    data_path = os.path.join(a.task_dir, "aime_100.jsonl")
    with open(data_path, "w") as fo:
        for r in sel:
            fo.write(json.dumps(r, ensure_ascii=False) + "\n")

    # scorer: symlink, never a copy — one canonical extractor
    link = os.path.join(a.task_dir, "utils_chat.py")
    target = os.path.join("..", "aime24_chat", "utils_chat.py")
    if os.path.islink(link) or os.path.exists(link):
        os.remove(link)
    os.symlink(target, link)

    _write_yaml(a.task_dir, a.seed)

    got = collections.Counter(r["year"] for r in sel)
    report = dict(n=len(sel), span=[a.year_min, a.year_max], seed=a.seed,
                  source="gneubig/aime-1983-2024",
                  train_pool=a.train_pool, train_ids_excluded_total=len(train_ids),
                  excluded_as_training_in_span=excluded, malformed=malformed,
                  clean_available_per_year=avail, selected_per_year=dict(sorted(got.items())),
                  disjoint_from_aime_30="by year — aime_30 is Maxwell-Jia/AIME_2024, this set stops at 2023",
                  id_note="id = <excl_key>-<sha1(question)[:6]>; excl_key collides between "
                          "AIME I/II of a year, so it is used only for the (conservative) "
                          "training exclusion, never as a unique row key",
                  ids=[r["id"] for r in sel])
    with open(os.path.join(a.task_dir, "build_report.json"), "w") as fo:
        json.dump(report, fo, indent=2)

    assert not ({r["excl_key"] for r in sel} & train_ids), "TRAINING LEAK — refusing"
    assert len({r["id"] for r in sel}) == len(sel), "duplicate ids"
    assert len({r["Problem"] for r in sel}) == len(sel), "duplicate problem text"
    print(">>> data   -> %s (%d problems, per-year %s)" % (data_path, len(sel), dict(sorted(got.items()))))
    print(">>> task   -> %s/aime100_chat.yaml" % a.task_dir)
    print(">>> report -> %s/build_report.json" % a.task_dir)
    print(">>> disjointness asserted: 0 overlap with %d aime_hist training ids; 0 x 2024" % len(train_ids))


if __name__ == "__main__":
    main()
