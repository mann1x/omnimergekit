#!/usr/bin/env bash
# install-git-hooks.sh — install the gitleaks-backed pre-commit secret gate.
#
# .git/hooks is NOT tracked by git, so a fresh clone has no hooks. Run this once
# after cloning to wire up the staged-secret scan:
#
#     bash scripts/install-git-hooks.sh
#
# The hook blocks any commit whose STAGED diff contains a secret (HF token, API
# key, high-entropy string, ...), per .gitleaks.toml. Requires the `gitleaks`
# binary on PATH (https://github.com/gitleaks/gitleaks/releases). If gitleaks is
# absent the hook warns loudly and does NOT silently pass.
#
# The gate is ONE marked block in .git/hooks/pre-commit, placed first (right
# after the shebang) so a leak stops the commit before any other block runs.
# Every other block (e.g. Caliber's `# caliber:pre-commit:start ... end`) is
# left untouched: re-running this installer updates only its own block.
# Same semantics as claude-hooks `scripts/secret_scan.py --install-hook`.
#
# Origin: 2026-05-23 — a live HF token leaked via a `${HF_TOKEN:-<literal>}`
# fallback in scripts/pod_quant_31b.sh, pushed to this public repo. This gate
# makes that class of mistake un-committable.
# 2026-10-25: was `cat > pre-commit`, which wiped any other tool's block on
# every re-install; now marker-managed.
set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
HOOK="$(git rev-parse --git-common-dir)/hooks/pre-commit"
case "$HOOK" in /*) ;; *) HOOK="$REPO_ROOT/$HOOK" ;; esac
BLOCK_FILE="$(mktemp)"
trap 'rm -f "$BLOCK_FILE"' EXIT

cat > "$BLOCK_FILE" <<'HOOK_EOF'
# >>> omnimergekit gitleaks gate (scripts/install-git-hooks.sh) >>>
# Edit the generator, not this block (it is replaced on re-install).
if ! command -v gitleaks >/dev/null 2>&1; then
    echo "⚠ gitleaks not found on PATH — STAGED SECRET SCAN SKIPPED." >&2
    echo "  Install it, then re-run: bash scripts/install-git-hooks.sh" >&2
    echo "  (Refusing to silently allow an unscanned commit would block all work;" >&2
    echo "   this is a loud warning instead. Install gitleaks to restore the gate.)" >&2
elif ! gitleaks git --staged --redact --no-banner -c "$(git rev-parse --show-toplevel)/.gitleaks.toml"; then
    # Scan only the staged diff (fast). --redact keeps any detected secret out of the output.
    echo >&2
    echo "✖ gitleaks: a secret was detected in your STAGED changes — commit aborted." >&2
    echo "  • Never hardcode a token. Use an env var that fails loud if unset:" >&2
    echo "        export HF_TOKEN=\"\${HF_TOKEN:?HF_TOKEN must be exported}\"" >&2
    echo "  • If this is a genuine false positive, add an allowlist entry to" >&2
    echo "    .gitleaks.toml and re-stage." >&2
    exit 1
fi
# <<< omnimergekit gitleaks gate <<<
HOOK_EOF

mkdir -p "$(dirname "$HOOK")"
python3 - "$HOOK" "$BLOCK_FILE" <<'PY'
import sys
from pathlib import Path

hook, block = Path(sys.argv[1]), Path(sys.argv[2]).read_text()
start = "# >>> omnimergekit gitleaks gate"
end = "# <<< omnimergekit gitleaks gate <<<\n"
# The pre-2026-10-25 installer wrote the whole file; its gate ended at the first
# `fi` after the gitleaks call. Anything after that belongs to another tool.
legacy = "# AUTO-GENERATED by scripts/install-git-hooks.sh"
text = hook.read_text() if hook.exists() else ""

if block in text:
    print("current")
    sys.exit(0)
if start in text and end in text:
    head, _, rest = text.partition(start)
    _, _, tail = rest.partition(end)
    new, what = head + block + tail, "updated"
else:
    what = "installed"
    if legacy in text:
        lines = text.splitlines(keepends=True)
        i = next(n for n, l in enumerate(lines) if legacy in l)
        g = next(n for n in range(i, len(lines)) if "gitleaks git --staged" in lines[n])
        j = next(n for n in range(g, len(lines)) if lines[n].rstrip() == "fi")
        keep = [l for l in lines[:i] + lines[j + 1:]
                if l.strip() != 'REPO_ROOT="$(git rev-parse --show-toplevel)"']
        text, what = "".join(keep), "migrated"
    if not text.strip() or text.strip() == "#!/usr/bin/env bash":
        new = "#!/usr/bin/env bash\n" + block
    elif text.startswith("#!"):
        first, _, rest = text.partition("\n")
        new = f"{first}\n{block}{rest.lstrip(chr(10))}"
    else:
        new = block + text
hook.write_text(new)
hook.chmod(hook.stat().st_mode | 0o111)
print(what)
PY

echo "✓ gitleaks gate in pre-commit hook → $HOOK"
if command -v gitleaks >/dev/null 2>&1; then
    echo "✓ gitleaks present: $(gitleaks version)"
else
    echo "⚠ gitleaks NOT on PATH — install it so the hook can actually scan:"
    echo "    https://github.com/gitleaks/gitleaks/releases  (binary → /usr/local/bin/gitleaks)"
fi
